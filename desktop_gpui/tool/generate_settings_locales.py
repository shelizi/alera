#!/usr/bin/env python3
"""Generate GPUI Settings locales from Classic's source-string translations.

Do not edit the generated ui.yml directly; add preview-only terminology to
locales/settings_overrides.json. Both the import and audit are deterministic.
"""
import json
import re
import sys
from pathlib import Path

PACKAGE = Path(__file__).resolve().parents[1]
ROOT = PACKAGE.parent
CATALOG = PACKAGE / "src" / "settings_menu_catalog.rs"
OUTPUT = PACKAGE / "locales" / "ui.yml"
OVERRIDES = PACKAGE / "locales" / "settings_overrides.json"
LOCALIZATIONS = ROOT / "lib" / "src" / "app" / "localization"
CATALOG_UI_SOURCE = PACKAGE / "src" / "native_settings_catalog_ui.rs"

STRING = r'"((?:\\.|[^"\\])*)"'
DART_ENTRY = re.compile(r"'((?:\\.|[^'\\])*)'\s*:\s*'((?:\\.|[^'\\])*)'", re.S)

def rust_string(s: str) -> str:
    return s.replace(r'\"', '"').replace("\\\\", "\\")

def dart_string(s: str) -> str:
    return s.replace(r"\'", "'").replace("\\\\", "\\")

def catalog_strings() -> list[str]:
    text = CATALOG.read_text(encoding="utf-8")
    keys = set()
    # Section titles/descriptions, group captions, and row title + help text.
    for m in re.finditer(r'(?:title|description):\s*' + STRING, text):
        keys.add(rust_string(m.group(1)))
    for m in re.finditer(r'group!\(\s*' + STRING, text):
        keys.add(rust_string(m.group(1)))
    for m in re.finditer(r'row!\(\s*' + STRING + r'\s*,\s*' + STRING, text, re.S):
        keys.update([rust_string(m.group(1)), rust_string(m.group(2))])
    ui_text = CATALOG_UI_SOURCE.read_text(encoding="utf-8")
    for m in re.finditer(r'\btr\(\s*(?:locale|self\.settings_menu_locale)\s*,\s*' + STRING, ui_text):
        keys.add(rust_string(m.group(1)))
    keys.update((
        "Settings", "Preferences", "Resources", "Search settings",
        "No matching settings.", "Select…", "Open",
        "UI preview only · controls are not connected to settings",
        "Native desktop · Preview",
        "Connected Native Controls",
        "Catalog preview only · existing Native controls below may change settings",
        "Refresh",
        "Running Agent sessions (Runtime Host)",
        "Host Agent Profiles",
        "Managed",
        "Command",
        "Enabled", "Disabled", "days (0 disables)",
        "change via language selector", "edit in Classic",
    ))
    if len(keys) < 100:
        raise RuntimeError(f"Catalog extraction unexpectedly small: {len(keys)}")
    return sorted(keys, key=str.casefold)

def classic_translations() -> dict[str, dict[str, str]]:
    result = {}
    for locale, pattern in (
        ("zh-TW", "alera_localizations_zh*.dart"),
        ("zh-CN", "alera_localizations_zh_cn*.dart"),
        ("ja", "alera_localizations_ja*.dart"),
    ):
        merged = {}
        files = sorted(LOCALIZATIONS.glob(pattern))
        if locale == "zh-TW":
            files = [p for p in files if "_zh_cn" not in p.name]
        for file in files:
            content = file.read_text(encoding="utf-8")
            for key, val in DART_ENTRY.findall(content):
                merged[dart_string(key)] = dart_string(val)
        # The root file also carries strings common to shell, settings, and UI.
        common = (LOCALIZATIONS / "alera_localizations.dart").read_text(encoding="utf-8")
        method = {"zh-TW": "_traditionalChinese", "zh-CN": "_simplifiedChinese", "ja": "_japanese"}[locale]
        fragment = common.split(f"static const Map<String, String> {method}", 1)[1].split("\n  };", 1)[0]
        for key, val in DART_ENTRY.findall(fragment):
            merged[dart_string(key)] = dart_string(val)
        result[locale] = merged
    return result

def yaml_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)

def main() -> None:
    keys = catalog_strings()
    trans = classic_translations()
    custom = json.loads(OVERRIDES.read_text(encoding="utf-8"))
    if not isinstance(custom, dict):
        raise RuntimeError("Overrides must be an object keyed by Classic English source strings.")
    unused = set(custom) - set(keys)
    if unused:
        raise RuntimeError(f"Unused override keys: {sorted(unused)}")
    lines = ["# GENERATED by tool/generate_settings_locales.py. Do not hand-edit.", "_version: 2"]
    missing = {locale: [] for locale in trans}
    for key in keys:
        lines.extend([f"{yaml_str(key)}:", f"  en: {yaml_str(key)}"])
        for locale in ("zh-TW", "zh-CN", "ja"):
            value = custom.get(key, {}).get(locale) or trans[locale].get(key)
            if value:
                lines.append(f"  {locale}: {yaml_str(value)}")
            else:
                missing[locale].append(key)
    generated = "\n".join(lines) + "\n"
    if "--check" in sys.argv:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != generated:
            raise SystemExit("Generated locale catalog is stale; run python tool/generate_settings_locales.py")
    else:
        OUTPUT.write_text(generated, encoding="utf-8")
    for locale, absent in missing.items():
        print(f"{locale}: {len(keys)-len(absent)}/{len(keys)} translated; {len(absent)} fallback to English")
        if absent:
            print("  Missing: " + ", ".join(absent[:40]))
    if "--check" in sys.argv and any(missing.values()):
        raise SystemExit("Missing Settings translations; update Classic dictionaries or settings_overrides.json")
    print(f"{'Checked' if '--check' in sys.argv else 'Wrote'} {OUTPUT} ({len(keys)} strings)")

if __name__ == "__main__":
    main()
